/// Python backend for cddlc.
///
/// Emits a Python package:
///   <module>-cbor/
///     pyproject.toml            ← PEP 517, cbor2, pytest
///     src/<module>.py           ← dataclasses + encode/decode
///     tests/test_roundtrip.py   ← pytest roundtrip tests
use cddlc_codegen::{
    to_pascal_case, to_snake_case, Backend, CodegenError, CodegenOptions, CodegenOutput,
    GeneratedFile, IndentWriter,
};
use cddlc_ir::{
    AliasDef, ArrayDef, Constraint, EnumDef, EnumVariant, IrModule, LiteralValue, MapDef,
    Occurrence, Primitive, StructDef, TypeDef, TypeRef,
};

pub struct PythonBackend;

impl Backend for PythonBackend {
    fn language_name(&self) -> &str {
        "Python"
    }
    fn file_extension(&self) -> &str {
        "py"
    }

    fn generate(
        &self,
        module: &IrModule,
        opts: &CodegenOptions,
    ) -> Result<CodegenOutput, CodegenError> {
        cddlc_codegen::check_rest_keys(module, opts, "Python", true)?;
        let name = module.name.as_str();
        let fmt_tag = if opts.is_json() { "json" } else { "cbor" };
        let crate_dir = format!("{name}-{fmt_tag}");
        let mod_name = py_module_name(name);

        Ok(CodegenOutput {
            files: vec![
                GeneratedFile {
                    path: format!("{crate_dir}/pyproject.toml"),
                    content: emit_pyproject(name, opts),
                },
                GeneratedFile {
                    path: format!("{crate_dir}/src/{mod_name}.py"),
                    content: emit_source(module, opts),
                },
                GeneratedFile {
                    path: format!("{crate_dir}/tests/test_roundtrip.py"),
                    content: emit_tests(module, opts),
                },
            ],
        })
    }
}

// ── pyproject.toml ────────────────────────────────────────────────────────────

fn emit_pyproject(name: &str, opts: &CodegenOptions) -> String {
    let pkg_name = name.replace('_', "-");
    let fmt_tag = if opts.is_json() { "json" } else { "cbor" };
    let deps: String = if opts.is_json() {
        "    # json and base64 are stdlib — no extra runtime needed".into()
    } else {
        "    \"cbor2>=6.0\",  # semantic_decoders keeps tags raw".into()
    };
    let header = cddlc_codegen::header_text(opts, cddlc_codegen::CommentStyle::Hash);
    format!(
        r#"{header}[build-system]
requires      = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name        = "{pkg_name}-{fmt_tag}"
version     = "0.1.0"
description = "@generated by cddlc"
requires-python = ">=3.11"
dependencies = [
{deps}
]

[project.optional-dependencies]
dev = [
    "pytest>=8.0",
    "pytest-cov>=5.0",
]

[tool.pytest.ini_options]
testpaths = ["tests"]

[tool.setuptools.packages.find]
where = ["src"]
"#
    )
}

// ── Source file ───────────────────────────────────────────────────────────────
//
// Every generated type has `_to_raw()` (to plain Python values: dict, list, int,
// str, bytes, `cbor2.CBORTag`, ...) and `_from_raw(raw)` (back, with type checks
// and validation). `encode()` / `decode()` only add the format, so nested types,
// tags and JSON's base64url bytes are handled in one place (dgtlrift/cddlc#48).

/// CBOR helpers. cbor2 turns some tags into its own objects (tag 1 into a
/// `datetime`); `semantic_decoders` (cbor2 >= 6) keeps every tag the module uses
/// as a raw `CBORTag`.
const CBOR_HELPERS: &str = r#"def _raw_tag(tag: int) -> Any:
    def decode(value: Any, _immutable: bool) -> Any:
        return cbor2.CBORTag(tag, value)
    return decode


def _loads(data: bytes) -> Any:
    return cbor2.loads(data, semantic_decoders=_SEMANTIC_DECODERS)


class _Float:
    """A float that encodes at a fixed CBOR width: cbor2 writes every Python
    float as float64, but a float16/float32 field must use its own width."""

    __slots__ = ("value", "head", "fmt")

    def __init__(self, value: float, head: bytes, fmt: str) -> None:
        self.value = value
        self.head = head
        self.fmt = fmt


def _f16(v: float) -> _Float:
    return _Float(v, b"\xf9", ">e")


def _f32(v: float) -> _Float:
    return _Float(v, b"\xfa", ">f")


def _default(encoder: Any, value: Any) -> None:
    if isinstance(value, _Float):
        encoder.write(value.head + struct.pack(value.fmt, value.value))
        return
    raise cbor2.CBOREncodeTypeError(f"cannot encode {type(value).__name__}")


def _dumps(value: Any) -> bytes:
    return cbor2.dumps(value, default=_default)


def _tag(tag: int, value: Any) -> Any:
    return cbor2.CBORTag(tag, value)


def _untag(raw: Any, tag: int, at: str) -> Any:
    if not isinstance(raw, cbor2.CBORTag) or raw.tag != tag:
        raise ValueError(f"{at}: expected CBOR tag {tag}")
    return raw.value


def _bytes(v: Any, at: str) -> bytes:
    if not isinstance(v, bytes):
        raise ValueError(f"{at}: expected bytes, got {type(v).__name__}")
    return v"#;

/// JSON helpers: bytes are base64url strings without padding.
const JSON_HELPERS: &str = r#"def _loads(data: bytes) -> Any:
    return json.loads(data)


def _dumps(value: Any) -> bytes:
    return json.dumps(value).encode()


def _b64e(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def _bytes(v: Any, at: str) -> bytes:
    if not isinstance(v, str):
        raise ValueError(f"{at}: expected base64url text, got {type(v).__name__}")
    return base64.urlsafe_b64decode(v + "=" * (-len(v) % 4))"#;

/// Type checks shared by both formats.
const CHECK_HELPERS: &str = r#"def _bits_ok(v: Any, m: bytes) -> bool:
    """`.bits`: only the bits `m` has set may be set (bit n is bit n % 8 of byte n / 8)."""
    if isinstance(v, (bytes, bytearray)):
        return all(b & ~(m[i] if i < len(m) else 0) == 0 for i, b in enumerate(v))
    if isinstance(v, bool) or not isinstance(v, int) or v < 0:
        return False
    return v & ~int.from_bytes(m, "little") == 0


def _int(v: Any, at: str) -> int:
    if isinstance(v, bool) or not isinstance(v, int):
        raise ValueError(f"{at}: expected an integer, got {type(v).__name__}")
    return v


def _float(v: Any, at: str) -> float:
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        raise ValueError(f"{at}: expected a number, got {type(v).__name__}")
    return float(v)


def _bool(v: Any, at: str) -> bool:
    if not isinstance(v, bool):
        raise ValueError(f"{at}: expected a bool, got {type(v).__name__}")
    return v


def _str(v: Any, at: str) -> str:
    if not isinstance(v, str):
        raise ValueError(f"{at}: expected text, got {type(v).__name__}")
    return v


def _null(v: Any, at: str) -> None:
    if v is not None:
        raise ValueError(f"{at}: expected null, got {type(v).__name__}")
    return None"#;

fn emit_source(module: &IrModule, opts: &CodegenOptions) -> String {
    let mut w = IndentWriter::new(4);

    for l in cddlc_codegen::header_comment(opts, cddlc_codegen::CommentStyle::Hash) {
        w.line(&l);
    }
    let fmt_label = if opts.is_json() {
        "JSON (RFC 8259)"
    } else {
        "CBOR (RFC 8949)"
    };
    w.line(&format!("# Format: {fmt_label}"));
    if opts.dcbor {
        w.line("# Encoding: deterministic (dCBOR)");
    }
    w.line("from __future__ import annotations");
    w.blank();
    if opts.is_json() {
        w.line("import base64");
        w.line("import json");
    } else {
        w.line("import cbor2");
        w.line("import struct");
    }
    w.line("from dataclasses import dataclass, field");
    w.line("from typing import Any, Literal, Optional");
    w.blank();
    w.blank();

    let helpers = if opts.is_json() {
        JSON_HELPERS
    } else {
        CBOR_HELPERS
    };
    for line in helpers
        .lines()
        .chain(["", "", ""])
        .chain(CHECK_HELPERS.lines())
    {
        if line.is_empty() {
            w.blank()
        } else {
            w.line(line)
        }
    }
    if !opts.is_json() {
        w.blank();
        w.blank();
        w.line("# Every CBOR tag this module uses is decoded as a raw CBORTag.");
        let tags = module_tags(module);
        let entries: Vec<String> = tags.iter().map(|t| format!("{t}: _raw_tag({t})")).collect();
        w.line(&format!("_SEMANTIC_DECODERS = {{{}}}", entries.join(", ")));
    }
    w.blank();
    w.blank();

    for (_, def) in &module.types {
        emit_type(&mut w, def, module, opts);
        w.blank();
        w.blank();
    }

    w.finish()
}

/// Every CBOR tag the module uses, on a type or inside a type reference.
fn module_tags(module: &IrModule) -> Vec<u64> {
    fn walk(ty: &TypeRef, out: &mut Vec<u64>) {
        match ty {
            TypeRef::Tagged(tag, inner) => {
                out.push(tag.0);
                walk(inner, out);
            }
            TypeRef::Choice(alts) => alts.iter().for_each(|t| walk(t, out)),
            TypeRef::Primitive(_) | TypeRef::Named(_) => {}
        }
    }
    let mut out = Vec::new();
    for (_, def) in &module.types {
        match def {
            TypeDef::Struct(s) => {
                out.extend(s.tagged.map(|t| t.0));
                s.fields.iter().for_each(|f| walk(&f.ty, &mut out));
            }
            TypeDef::Enum(e) => {
                out.extend(e.tagged.map(|t| t.0));
                e.variants.iter().for_each(|v| walk(&v.ty, &mut out));
            }
            TypeDef::Alias(a) => {
                out.extend(a.tagged.map(|t| t.0));
                walk(&a.ty, &mut out);
            }
            TypeDef::Array(a) => {
                out.extend(a.tagged.map(|t| t.0));
                walk(&a.element, &mut out);
            }
            TypeDef::Map(m) => {
                out.extend(m.tagged.map(|t| t.0));
                walk(&m.key_ty, &mut out);
                walk(&m.val_ty, &mut out);
            }
        }
    }
    out.sort_unstable();
    out.dedup();
    out
}

fn emit_type(w: &mut IndentWriter, def: &TypeDef, module: &IrModule, opts: &CodegenOptions) {
    match def {
        TypeDef::Struct(s) => emit_struct(w, s, opts),
        TypeDef::Enum(e) => emit_enum(w, e, opts),
        TypeDef::Array(a) => emit_array(w, a, flat_width(a, module), opts),
        TypeDef::Alias(a) => emit_alias(w, a, opts),
        TypeDef::Map(m) => emit_map(w, m, opts),
    }
}

/// `encode` / `decode`, shared by every type.
fn emit_encode_decode(w: &mut IndentWriter, class_name: &str) {
    w.line("def encode(self) -> bytes:");
    w.indent();
    w.line("return _dumps(self._to_raw())");
    w.dedent();
    w.blank();
    w.line("@classmethod");
    w.line(&format!(
        "def decode(cls, data: bytes) -> \"{class_name}\":"
    ));
    w.indent();
    w.line("return cls._from_raw(_loads(data))");
    w.dedent();
}

/// The `return` of a `_to_raw`, wrapped in the type's own tag (CBOR only).
fn return_tagged(
    w: &mut IndentWriter,
    tag: Option<cddlc_ir::CborTag>,
    expr: &str,
    opts: &CodegenOptions,
) {
    match tag {
        Some(t) if !opts.is_json() => w.line(&format!("return _tag({}, {expr})", t.0)),
        _ => w.line(&format!("return {expr}")),
    }
}

/// In a `_from_raw`, unwrap the type's own tag (CBOR only).
fn untag_raw(
    w: &mut IndentWriter,
    tag: Option<cddlc_ir::CborTag>,
    class_name: &str,
    opts: &CodegenOptions,
) {
    if let Some(t) = tag {
        if !opts.is_json() {
            w.line(&format!("raw = _untag(raw, {}, {class_name:?})", t.0));
        }
    }
}

/// Raises `ValueError` unless `expr` meets each constraint.
fn emit_constraint_checks(w: &mut IndentWriter, constraints: &[Constraint], expr: &str, at: &str) {
    for c in constraints {
        if let Some(check) = py_constraint_check(c, expr) {
            let msg = format!("{at}: {}", py_constraint_description(c));
            w.line(&format!("if not ({check}):"));
            w.indent();
            w.line(&format!("raise ValueError({msg:?})"));
            w.dedent();
        }
    }
}

