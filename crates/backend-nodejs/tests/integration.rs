    assert!(src.contains("const arr: unknown = expectTag(raw, 200, \"Stamps\");"), "{src}");

    // Nested named values are converted in place, never re-encoded.
    assert!(src.contains("fromCborTaggedSensor(m[\"inner\"])"), "{src}");
