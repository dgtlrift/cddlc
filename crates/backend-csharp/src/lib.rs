/// C# / .NET Core backend for cddlc.
///
/// Emits a .NET 8 library project:
///   <module>-cbor/
///     <module>-cbor.csproj   ← net8.0, System.Formats.Cbor, xUnit test ref
///     src/<Module>.cs        ← types + Encode/Decode
///     tests/RoundtripTests.cs ← xUnit roundtrip tests

use cddlc_codegen::{
    to_pascal_case, to_snake_case,
    Backend, CodegenError, CodegenOptions, CodegenOutput, GeneratedFile,
    IndentWriter,
};
use cddlc_ir::{
    AliasDef, ArrayDef, Constraint, EnumDef,
    IrModule, LiteralValue, Occurrence, Primitive, StructDef, TypeDef, TypeRef,
};

pub struct CSharpBackend;

impl Backend for CSharpBackend {
    fn language_name(&self) -> &str { "C#" }
    fn file_extension(&self) -> &str { "cs" }

    fn generate(
        &self,
        module: &IrModule,
        opts:   &CodegenOptions,
    ) -> Result<CodegenOutput, CodegenError> {
        let name      = module.name.as_str();
        let fmt_tag   = if opts.is_json() { "json" } else { "cbor" };
        let crate_dir = format!("{name}-{fmt_tag}");
        let ns        = to_pascal_case(name);

        Ok(CodegenOutput {
            files: vec![
                GeneratedFile {
                    path:    format!("{crate_dir}/{name}-{fmt_tag}.csproj"),
                    content: emit_csproj(name, opts),
                },
                GeneratedFile {
                    path:    format!("{crate_dir}/src/{ns}.cs"),
                    content: emit_source(module, opts),
                },
                GeneratedFile {
                    path:    format!("{crate_dir}/tests/RoundtripTests.cs"),
                    content: emit_tests(module, opts),
                },
            ],
        })
    }
}

// ── .csproj ───────────────────────────────────────────────────────────────────

fn emit_csproj(name: &str, opts: &CodegenOptions) -> String {
    let fmt_tag = if opts.is_json() { "json" } else { "cbor" };
    let ns = to_pascal_case(name);
    let cbor_ref = if opts.is_json() { "".into() } else {
        "  <ItemGroup>\n    <!-- CBOR runtime ships in-box with .NET 5+ -->\n    <PackageReference Include=\"System.Formats.Cbor\" Version=\"8.*\" />\n  </ItemGroup>\n\n".to_owned()
    };
    format!(r#"<!-- @generated by cddlc — do not edit manually -->
<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <TargetFramework>net8.0</TargetFramework>
    <Nullable>enable</Nullable>
    <ImplicitUsings>enable</ImplicitUsings>
    <AllowUnsafeBlocks>false</AllowUnsafeBlocks>
    <RootNamespace>{ns}</RootNamespace>
    <AssemblyName>{name}-{fmt_tag}</AssemblyName>
  </PropertyGroup>

{cbor_ref}  <ItemGroup Label="Test dependencies (only used by test project)">
    <PackageReference Include="Microsoft.NET.Test.Sdk" Version="17.*" />
    <PackageReference Include="xunit"                  Version="2.*" />
    <PackageReference Include="xunit.runner.visualstudio" Version="2.*" />
  </ItemGroup>
</Project>
"#)
}

// ── Source file ───────────────────────────────────────────────────────────────

fn emit_source(module: &IrModule, opts: &CodegenOptions) -> String {
    let name  = module.name.as_str();
    let ns    = to_pascal_case(name);
    let mut w = IndentWriter::new(4);

    for l in cddlc_codegen::header_lines(opts) {
        w.line(&format!("// {l}"));
    }
    let fmt_label = if opts.is_json() { "JSON (RFC 8259)" } else { "CBOR (RFC 8949)" };
    w.line(&format!("// Format: {fmt_label}"));
    if opts.dcbor { w.line("// Encoding: deterministic (dCBOR)"); }
    w.blank();
    w.line("using System;");
    w.line("using System.Collections.Generic;");
    if opts.is_json() {
        w.line("using System.Text.Json;");
        w.line("using System.Text.Json.Serialization;");
    } else {
        w.line("using System.Formats.Cbor;");
    }
    w.blank();
    w.line(&format!("namespace {ns};"));
    w.blank();

    // Emit error / helper type
    w.line("/// <summary>Field-level validation exception.</summary>");
    let exc_name = if opts.is_json() { "JsonValidationException" } else { "CborValidationException" };
    w.line(&format!("public sealed class {exc_name} : Exception"));
    w.line("{");
    w.indent();
    w.line("public string FieldName { get; }");
    w.line(&format!("public {exc_name}(string fieldName, string message)"));
    w.indent();
    w.line(": base($\"Validation failed for '{{fieldName}}': {{message}}\")");
    w.dedent();
    w.line("=> FieldName = fieldName;");
    w.dedent();
    w.line("}");
    w.blank();

    // JSON: emit base64url helpers
    if opts.is_json() {
        w.line("internal static class Base64Url");
        w.line("{");
        w.indent();
        w.line("public static string Encode(byte[] data)");
        w.indent();
        w.line("=> Convert.ToBase64String(data).Replace('+', '-').Replace('/', '_').TrimEnd('=');");
        w.dedent();
        w.blank();
        w.line("public static byte[] Decode(string s)");
        w.line("{");
        w.indent();
        w.line("s = s.Replace('-', '+').Replace('_', '/');");
        w.line("switch (s.Length % 4) { case 2: s += \"==\"; break; case 3: s += \"=\"; break; }");
        w.line("return Convert.FromBase64String(s);");
        w.dedent();
        w.line("}");
        w.dedent();
        w.line("}");
        w.blank();
    }

    // Emit each type
    for (_, def) in &module.types {
        emit_type(&mut w, def, opts);
        w.blank();
    }

    w.finish()
}

fn emit_type(w: &mut IndentWriter, def: &TypeDef, opts: &CodegenOptions) {
    match def {
        TypeDef::Struct(s) => emit_struct(w, s, opts),
        TypeDef::Enum(e)   => emit_enum(w, e, opts),
        TypeDef::Array(a)  => emit_array(w, a, opts),
        TypeDef::Alias(a)  => emit_alias(w, a, opts),
        TypeDef::Map(_)    => {}
    }
}

// ── Class (struct) ────────────────────────────────────────────────────────────

fn emit_struct(w: &mut IndentWriter, s: &StructDef, opts: &CodegenOptions) {
    emit_doc_comment(w, s.doc.as_deref());
    if s.deprecated { w.line("[Obsolete]"); }

    let type_name = to_pascal_case(&s.name);

    w.line(&format!("public sealed class {type_name}"));
    w.line("{");
    w.indent();

    // Properties
    for f in &s.fields {
        emit_doc_comment(w, f.doc.as_deref());
        if f.deprecated { w.line("[Obsolete]"); }
        if opts.is_json() {
            // JsonPropertyName attribute
            w.line(&format!("[JsonPropertyName({:?})]", f.name.as_str()));
            // Skip null for optional fields
            if matches!(f.occurrence, Occurrence::Optional) {
                w.line("[JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]");
            }
        }
        let ty    = cs_field_type(&f.ty, &f.occurrence, opts);
        let pname = to_pascal_case(&f.name);
        w.line(&format!("public {ty} {pname} {{ get; set; }}"));
    }
    w.blank();

    // Encode method
    emit_struct_encode(w, s, opts);
    w.blank();

    // Decode static method
    emit_struct_decode(w, s, opts);

    w.dedent();
    w.line("}");
}

fn emit_struct_encode(w: &mut IndentWriter, s: &StructDef, opts: &CodegenOptions) {
    if opts.is_json() {
        w.line("public byte[] ToJson()");
        w.indent();
        w.line("=> JsonSerializer.SerializeToUtf8Bytes(this);");
        w.dedent();
        return;
    }

    let field_count = s.fields.len();

    w.line("public void Encode(CborWriter writer)");
    w.line("{");
    w.indent();

    // Tag
    if let Some(tag) = s.tagged {
        w.line(&format!("writer.WriteTag((CborTag){});", tag.0));
    }

    // dCBOR: sort fields by key
    let fields: Vec<_> = if opts.dcbor {
        let mut fs: Vec<_> = s.fields.iter().collect();
        fs.sort_by(|a, b| a.name.cmp(&b.name));
        fs
    } else {
        s.fields.iter().collect()
    };

    w.line(&format!("writer.WriteStartMap({field_count});"));
    for f in &fields {
        let pname = to_pascal_case(&f.name);
        w.line(&format!("writer.WriteTextString({:?});", f.name.as_str()));
        emit_cs_encode_value(w, &f.ty, &format!("this.{pname}"), &f.occurrence, opts);
    }
    w.line("writer.WriteEndMap();");

    w.dedent();
    w.line("}");
}

fn emit_struct_decode(w: &mut IndentWriter, s: &StructDef, opts: &CodegenOptions) {
    let type_name = to_pascal_case(&s.name);

    if opts.is_json() {
        w.line(&format!("public static {type_name} FromJson(byte[] data)"));
        w.indent();
        w.line(&format!("=> JsonSerializer.Deserialize<{type_name}>(data)!;"));
        w.dedent();
        return;
    }

    w.line(&format!("public static {type_name} Decode(CborReader reader)"));
    w.line("{");
    w.indent();

    // Tag verification
    if let Some(tag) = s.tagged {
        w.line(&format!("var tag = reader.ReadTag();"));
        w.line(&format!("if ((ulong)tag != {}) throw new CborContentException(\"Unexpected CBOR tag\");", tag.0));
    }

    // Declare locals
    for f in &s.fields {
        let ty    = cs_field_type(&f.ty, &f.occurrence, opts);
        let local = to_snake_case(&f.name);
        let def   = cs_default_value(&f.ty, &f.occurrence, opts);
        w.line(&format!("{ty} {local} = {def};"));
    }
    w.blank();

    w.line("var length = reader.ReadStartMap();");
    w.line("var count  = length ?? int.MaxValue;");
    w.line("for (int i = 0; i < count; i++)");
    w.line("{");
    w.indent();
    w.line("if (length == null && reader.PeekState() == CborReaderState.EndMap) break;");
    w.line("var key = reader.ReadTextString();");
    w.line("switch (key)");
    w.line("{");
    w.indent();

    for f in &s.fields {
        let local  = to_snake_case(&f.name);
        let fkey   = f.name.as_str();
        w.line(&format!("case {:?}:", fkey));
        w.indent();
        emit_cs_decode_field(w, &f.ty, &local, &f.constraints, &f.name, &f.occurrence, opts);
        w.line("break;");
        w.dedent();
    }

    // Unknown fields — skip
    w.line("default:");
    w.indent();
    w.line("reader.SkipValue();");
    w.line("break;");
    w.dedent();

    w.dedent();
    w.line("}"); // switch
    w.dedent();
    w.line("}"); // for
    w.line("reader.ReadEndMap();");
    w.blank();

    w.line(&format!("return new {type_name}"));
    w.line("{");
    w.indent();
    for f in &s.fields {
        let pname = to_pascal_case(&f.name);
        let local = to_snake_case(&f.name);
        w.line(&format!("{pname} = {local},"));
    }
    w.dedent();
    w.line("};");

    w.dedent();
    w.line("}");
}

// ── Enum (sealed class hierarchy) ─────────────────────────────────────────────

fn emit_enum(w: &mut IndentWriter, e: &EnumDef, opts: &CodegenOptions) {
    if opts.is_json() {
        emit_enum_json(w, e);
        return;
    }
    emit_doc_comment(w, e.doc.as_deref());
    if e.deprecated { w.line("[Obsolete]"); }

    let type_name = to_pascal_case(&e.name);

    w.line(&format!("public abstract class {type_name}"));
    w.line("{");
    w.indent();

    // Sealed subclasses
    for v in &e.variants {
        let vname = to_pascal_case(&v.name);
        match &v.ty {
            TypeRef::Primitive(Primitive::Null) => {
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public static readonly {vname} Instance = new();"));
                w.line(&format!("public override void Encode(CborWriter writer) => writer.WriteTextString({:?});",
                    v.name.to_lowercase().replace('_', "-")));
                w.dedent();
                w.line("}");
            }
            TypeRef::Primitive(Primitive::Tstr) => {
                let cddl_str = v.name.to_lowercase().replace('_', "-");
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public static readonly {vname} Instance = new();"));
                w.line(&format!("public override void Encode(CborWriter writer) => writer.WriteTextString({:?});", cddl_str));
                w.dedent();
                w.line("}");
            }
            TypeRef::Primitive(p) => {
                let ct = cs_primitive(p);
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public {ct} Value {{ get; }}"));
                w.line(&format!("public {vname}({ct} value) => Value = value;"));
                emit_variant_encode(w, p, "Value");
                w.dedent();
                w.line("}");
            }
            TypeRef::Named(n) => {
                let ct = to_pascal_case(n);
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public {ct} Value {{ get; }}"));
                w.line(&format!("public {vname}({ct} value) => Value = value;"));
                w.line("public override void Encode(CborWriter writer) => Value.Encode(writer);");
                w.dedent();
                w.line("}");
            }
            _ => {
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public static readonly {vname} Instance = new();"));
                w.line("public override void Encode(CborWriter writer) => writer.WriteNull();");
                w.dedent();
                w.line("}");
            }
        }
        w.blank();
    }

    // Abstract encode
    w.line("public abstract void Encode(CborWriter writer);");
    w.blank();

    // Static decode
    w.line(&format!("public static {type_name} Decode(CborReader reader)"));
    w.line("{");
    w.indent();

    if let Some(tag) = e.tagged {
        w.line("var tag = reader.ReadTag();");
        w.line(&format!("if ((ulong)tag != {}) throw new CborContentException(\"Unexpected CBOR tag\");", tag.0));
    }

    // Peek at the major type
    w.line("var state = reader.PeekState();");
    w.line("if (state == CborReaderState.TextString)");
    w.line("{");
    w.indent();
    w.line("var s = reader.ReadTextString();");
    w.line("return s switch");
    w.line("{");
    w.indent();
    for v in &e.variants {
        if matches!(&v.ty, TypeRef::Primitive(Primitive::Tstr | Primitive::Null)) {
            let vname    = to_pascal_case(&v.name);
            let cddl_str = v.name.to_lowercase().replace('_', "-");
            w.line(&format!("{:?} => {vname}.Instance,", cddl_str));
        }
    }
    w.line("_ => throw new CborContentException($\"Unknown {type_name} variant: {s}\"),");
    w.dedent();
    w.line("};");
    w.dedent();
    w.line("}");

    // Integer variants
    let has_int = e.variants.iter().any(|v|
        matches!(&v.ty, TypeRef::Primitive(Primitive::Uint | Primitive::Int)));
    if has_int {
        w.line("else if (state == CborReaderState.UnsignedInteger || state == CborReaderState.NegativeInteger)");
        w.line("{");
        w.indent();
        for v in &e.variants {
            match &v.ty {
                TypeRef::Primitive(Primitive::Uint) => {
                    let vname = to_pascal_case(&v.name);
                    w.line(&format!("return new {vname}(reader.ReadUInt64());"));
                    break;
                }
                TypeRef::Primitive(Primitive::Int) => {
                    let vname = to_pascal_case(&v.name);
                    w.line(&format!("return new {vname}(reader.ReadInt64());"));
                    break;
                }
                _ => {}
            }
        }
        w.dedent();
        w.line("}");
    }

    w.line(&format!("throw new CborContentException(\"Cannot decode {type_name}\");"));

    w.dedent();
    w.line("}");

    w.dedent();
    w.line("}");
}

fn emit_enum_json(w: &mut IndentWriter, e: &EnumDef) {
    emit_doc_comment(w, e.doc.as_deref());
    if e.deprecated { w.line("[Obsolete]"); }

    let type_name = to_pascal_case(&e.name);

    w.line(&format!("public abstract class {type_name}"));
    w.line("{");
    w.indent();

    // Sealed subclasses
    for v in &e.variants {
        let vname    = to_pascal_case(&v.name);
        let cddl_str = v.name.to_lowercase().replace('_', "-");
        match &v.ty {
            TypeRef::Primitive(Primitive::Null | Primitive::Tstr) => {
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public static readonly {vname} Instance = new();"));
                w.line(&format!("public override byte[] ToJson() => System.Text.Encoding.UTF8.GetBytes({cddl_str:?}.PadLeft(0));"));
                w.dedent();
                w.line("}");
            }
            TypeRef::Primitive(p) => {
                let ct = cs_primitive(p);
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public {ct} Value {{ get; }}"));
                w.line(&format!("public {vname}({ct} value) => Value = value;"));
                w.line("public override byte[] ToJson() => JsonSerializer.SerializeToUtf8Bytes(Value);");
                w.dedent();
                w.line("}");
            }
            TypeRef::Named(n) => {
                let ct = to_pascal_case(n);
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public {ct} Value {{ get; }}"));
                w.line(&format!("public {vname}({ct} value) => Value = value;"));
                w.line("public override byte[] ToJson() => Value.ToJson();");
                w.dedent();
                w.line("}");
            }
            _ => {
                w.line(&format!("public sealed class {vname} : {type_name}"));
                w.line("{");
                w.indent();
                w.line(&format!("public static readonly {vname} Instance = new();"));
                w.line("public override byte[] ToJson() => \"null\"u8.ToArray();");
                w.dedent();
                w.line("}");
            }
        }
        w.blank();
    }

    // Factory methods
    for v in &e.variants {
        let vname    = to_pascal_case(&v.name);
        let cddl_str = v.name.to_lowercase().replace('_', "-");
        match &v.ty {
            TypeRef::Primitive(Primitive::Null | Primitive::Tstr) => {
                w.line(&format!("public static {vname} Create{vname}(string _ = {cddl_str:?}) => {vname}.Instance;"));
            }
            TypeRef::Primitive(p) => {
                let ct = cs_primitive(p);
                w.line(&format!("public static {vname} Create{vname}({ct} value) => new(value);"));
            }
            TypeRef::Named(n) => {
                let ct = to_pascal_case(n);
                w.line(&format!("public static {vname} Create{vname}({ct} value) => new(value);"));
            }
            _ => {
                w.line(&format!("public static {vname} Create{vname}() => {vname}.Instance;"));
            }
        }
    }
    w.blank();

    w.line("public abstract byte[] ToJson();");
    w.blank();

    // FromJson: parse JSON and dispatch
    w.line(&format!("public static {type_name} FromJson(byte[] data)"));
    w.line("{");
    w.indent();
    w.line("using var doc = JsonDocument.Parse(data);");
    w.line("var root = doc.RootElement;");
    w.line("if (root.ValueKind == JsonValueKind.String)");
    w.line("{");
    w.indent();
    w.line("var s = root.GetString()!;");
    w.line("return s switch");
    w.line("{");
    w.indent();
    for v in &e.variants {
        if matches!(&v.ty, TypeRef::Primitive(Primitive::Tstr | Primitive::Null)) {
            let vname    = to_pascal_case(&v.name);
            let cddl_str = v.name.to_lowercase().replace('_', "-");
            w.line(&format!("{cddl_str:?} => {vname}.Instance,"));
        }
    }
    w.line(&format!("_ => throw new JsonException($\"Unknown {type_name} variant: {{s}}\"),"));
    w.dedent();
    w.line("};");
    w.dedent();
    w.line("}");
    let has_int = e.variants.iter().any(|v|
        matches!(&v.ty, TypeRef::Primitive(Primitive::Uint | Primitive::Int)));
    if has_int {
        w.line("if (root.ValueKind == JsonValueKind.Number)");
        w.line("{");
        w.indent();
        for v in &e.variants {
            match &v.ty {
                TypeRef::Primitive(Primitive::Uint) => {
                    let vname = to_pascal_case(&v.name);
                    w.line(&format!("return new {vname}(root.GetUInt64());"));
                    break;
                }
                TypeRef::Primitive(Primitive::Int) => {
                    let vname = to_pascal_case(&v.name);
                    w.line(&format!("return new {vname}(root.GetInt64());"));
                    break;
                }
                _ => {}
            }
        }
        w.dedent();
        w.line("}");
    }
    w.line(&format!("throw new JsonException(\"Cannot decode {type_name}\");"));
    w.dedent();
    w.line("}");

    w.dedent();
    w.line("}");
}

fn emit_variant_encode(w: &mut IndentWriter, p: &Primitive, field: &str) {
    let call = match p {
        Primitive::Bool  => format!("writer.WriteBoolean({field})"),
        Primitive::Uint  => format!("writer.WriteUInt64({field})"),
        Primitive::Int   => format!("writer.WriteInt64({field})"),
        Primitive::Float32 | Primitive::Float16 => format!("writer.WriteSingle({field})"),
        Primitive::Float64 | Primitive::Float   => format!("writer.WriteDouble({field})"),
        Primitive::Tstr  => format!("writer.WriteTextString({field})"),
        Primitive::Bstr | Primitive::Any => format!("writer.WriteByteString({field})"),
        Primitive::Null | Primitive::Undefined => "writer.WriteNull()".into(),
    };
    w.line(&format!("public override void Encode(CborWriter writer) => {call};"));
}

// ── Array ─────────────────────────────────────────────────────────────────────

fn emit_array(w: &mut IndentWriter, a: &ArrayDef, opts: &CodegenOptions) {
    emit_doc_comment(w, a.doc.as_deref());
    if a.deprecated { w.line("[Obsolete]"); }

    let type_name = to_pascal_case(&a.name);
    let elem_ty   = cs_typeref(&a.element, opts);

    w.line(&format!("public sealed class {type_name}"));
    w.line("{");
    w.indent();

    w.line(&format!("public List<{elem_ty}> Items {{ get; }} = new();"));
    w.blank();

    if opts.is_json() {
        w.line("public byte[] ToJson()");
        w.indent();
        w.line("=> JsonSerializer.SerializeToUtf8Bytes(Items);");
        w.dedent();
        w.blank();
        w.line(&format!("public static {type_name} FromJson(byte[] data)"));
        w.line("{");
        w.indent();
        w.line(&format!("var items = JsonSerializer.Deserialize<List<{elem_ty}>>(data)!;"));
        w.line(&format!("var result = new {type_name}();"));
        w.line("result.Items.AddRange(items);");
        w.line("return result;");
        w.dedent();
        w.line("}");
    } else {
        // Encode
        w.line("public void Encode(CborWriter writer)");
        w.line("{");
        w.indent();
        if let Some(tag) = a.tagged {
            w.line(&format!("writer.WriteTag((CborTag){});", tag.0));
        }
        w.line("writer.WriteStartArray(Items.Count);");
        w.line("foreach (var item in Items)");
        w.line("{");
        w.indent();
        emit_cs_encode_value(w, &a.element, "item", &Occurrence::Required, opts);
        w.dedent();
        w.line("}");
        w.line("writer.WriteEndArray();");
        w.dedent();
        w.line("}");
        w.blank();

        // Decode
        w.line(&format!("public static {type_name} Decode(CborReader reader)"));
        w.line("{");
        w.indent();
        if let Some(tag) = a.tagged {
            w.line("var tag = reader.ReadTag();");
            w.line(&format!("if ((ulong)tag != {}) throw new CborContentException(\"Unexpected CBOR tag\");", tag.0));
        }
        w.line(&format!("var result = new {type_name}();"));
        w.line("var length = reader.ReadStartArray();");
        w.line("var count  = length ?? int.MaxValue;");
        w.line("for (int i = 0; i < count; i++)");
        w.line("{");
        w.indent();
        w.line("if (length == null && reader.PeekState() == CborReaderState.EndArray) break;");
        let decode_expr = cs_decode_expr(&a.element, opts);
        w.line(&format!("result.Items.Add({decode_expr});"));
        w.dedent();
        w.line("}");
        w.line("reader.ReadEndArray();");
        w.line("return result;");
        w.dedent();
        w.line("}");
    }

    w.dedent();
    w.line("}");
}

// ── Alias ─────────────────────────────────────────────────────────────────────

fn emit_alias(w: &mut IndentWriter, a: &AliasDef, opts: &CodegenOptions) {
    emit_doc_comment(w, a.doc.as_deref());
    if a.deprecated { w.line("[Obsolete]"); }

    let type_name = to_pascal_case(&a.name);
    let inner     = cs_typeref(&a.ty, opts);
    let exc_name  = if opts.is_json() { "JsonValidationException" } else { "CborValidationException" };

    if a.constraints.is_empty() && a.tagged.is_none() {
        w.line(&format!("public sealed class {type_name}"));
        w.line("{");
        w.indent();
        w.line(&format!("public {inner} Value {{ get; set; }}"));
        w.blank();
        if opts.is_json() {
            w.line("public byte[] ToJson()");
            w.indent();
            w.line("=> JsonSerializer.SerializeToUtf8Bytes(Value);");
            w.dedent();
            w.blank();
            w.line(&format!("public static {type_name} FromJson(byte[] data)"));
            w.line("{");
            w.indent();
            w.line(&format!("return new {type_name} {{ Value = JsonSerializer.Deserialize<{inner}>(data)! }};"));
            w.dedent();
            w.line("}");
        } else {
            w.line("public void Encode(CborWriter writer)");
            w.line("{");
            w.indent();
            emit_cs_encode_value(w, &a.ty, "this.Value", &Occurrence::Required, opts);
            w.dedent();
            w.line("}");
            w.blank();
            w.line(&format!("public static {type_name} Decode(CborReader reader)"));
            w.line("{");
            w.indent();
            let decode_expr = cs_decode_expr(&a.ty, opts);
            w.line(&format!("return new {type_name} {{ Value = {decode_expr} }};"));
            w.dedent();
            w.line("}");
        }
        w.dedent();
        w.line("}");
        return;
    }

    // Constrained or tagged alias
    w.line(&format!("public sealed class {type_name}"));
    w.line("{");
    w.indent();

    w.line(&format!("private readonly {inner} _value;"));
    w.blank();
    w.line(&format!("public {inner} Value => _value;"));
    w.blank();

    // Constructor with validation
    w.line(&format!("public {type_name}({inner} value)"));
    w.line("{");
    w.indent();
    for c in &a.constraints {
        if let Some(check) = cs_constraint_check(c, "value") {
            let msg = constraint_description(c);
            w.line(&format!("if (!({check}))"));
            w.indent();
            w.line(&format!("throw new {exc_name}(nameof({type_name}), {msg:?});"));
            w.dedent();
        }
    }
    w.line("_value = value;");
    w.dedent();
    w.line("}");
    w.blank();

    if opts.is_json() {
        w.line("public byte[] ToJson()");
        w.indent();
        w.line("=> JsonSerializer.SerializeToUtf8Bytes(_value);");
        w.dedent();
        w.blank();
        w.line(&format!("public static {type_name} FromJson(byte[] data)"));
        w.line("{");
        w.indent();
        w.line(&format!("var raw = JsonSerializer.Deserialize<{inner}>(data)!;"));
        w.line(&format!("return new {type_name}(raw);"));
        w.dedent();
        w.line("}");
    } else {
        w.line("public void Encode(CborWriter writer)");
        w.line("{");
        w.indent();
        if let Some(tag) = a.tagged {
            w.line(&format!("writer.WriteTag((CborTag){});", tag.0));
        }
        emit_cs_encode_value(w, &a.ty, "this._value", &Occurrence::Required, opts);
        w.dedent();
        w.line("}");
        w.blank();

        w.line(&format!("public static {type_name} Decode(CborReader reader)"));
        w.line("{");
        w.indent();
        if let Some(tag) = a.tagged {
            w.line("var tag = reader.ReadTag();");
            w.line(&format!("if ((ulong)tag != {}) throw new CborContentException(\"Unexpected CBOR tag\");", tag.0));
        }
        let decode_expr = cs_decode_expr(&a.ty, opts);
        w.line(&format!("var raw = {decode_expr};"));
        w.line(&format!("return new {type_name}(raw);"));
        w.dedent();
        w.line("}");
    }

    w.dedent();
    w.line("}");
}

// ── Encode helpers ────────────────────────────────────────────────────────────

fn emit_cs_encode_value(
    w:    &mut IndentWriter,
    ty:   &TypeRef,
    expr: &str,
    occ:  &Occurrence,
    opts: &CodegenOptions,
) {
    match occ {
        Occurrence::Optional => {
            w.line(&format!("if ({expr} is not null)"));
            w.line("{");
            w.indent();
            emit_cs_encode_typeref(w, ty, expr, opts);
            w.dedent();
            w.line("} else { writer.WriteNull(); }");
        }
        Occurrence::ZeroOrMore { .. } | Occurrence::OneOrMore { .. }
        | Occurrence::Bounded { .. } => {
            // Collection — caller handles the loop
            emit_cs_encode_typeref(w, ty, expr, opts);
        }
        Occurrence::Required => {
            emit_cs_encode_typeref(w, ty, expr, opts);
        }
    }
}

fn emit_cs_encode_typeref(w: &mut IndentWriter, ty: &TypeRef, expr: &str, opts: &CodegenOptions) {
    match ty {
        TypeRef::Primitive(p) => {
            let call = cs_encode_call(p, expr);
            w.line(&format!("{call};"));
        }
        TypeRef::Named(_) => {
            w.line(&format!("{expr}.Encode(writer);"));
        }
        TypeRef::Tagged(tag, inner) => {
            w.line(&format!("writer.WriteTag((CborTag){});", tag.0));
            emit_cs_encode_typeref(w, inner, expr, opts);
        }
        TypeRef::Choice(_) => {
            w.line(&format!("{expr}.Encode(writer);"));
        }
    }
}

fn cs_encode_call(p: &Primitive, expr: &str) -> String {
    match p {
        Primitive::Bool      => format!("writer.WriteBoolean({expr})"),
        Primitive::Null | Primitive::Undefined => "writer.WriteNull()".into(),
        Primitive::Uint      => format!("writer.WriteUInt64({expr})"),
        Primitive::Int       => format!("writer.WriteInt64({expr})"),
        Primitive::Float16   => format!("writer.WriteSingle((float){expr})"),
        Primitive::Float32   => format!("writer.WriteSingle({expr})"),
        Primitive::Float64 | Primitive::Float => format!("writer.WriteDouble({expr})"),
        Primitive::Tstr      => format!("writer.WriteTextString({expr})"),
        Primitive::Bstr | Primitive::Any => format!("writer.WriteByteString({expr})"),
    }
}

// ── Decode helpers ────────────────────────────────────────────────────────────

fn emit_cs_decode_field(
    w:           &mut IndentWriter,
    ty:          &TypeRef,
    local:       &str,
    constraints: &[Constraint],
    field_name:  &str,
    occ:         &Occurrence,
    opts:        &CodegenOptions,
) {
    match occ {
        Occurrence::Optional => {
            w.line(&format!("if (reader.PeekState() == CborReaderState.Null) {{ reader.ReadNull(); {local} = null; }}"));
            w.line("else");
            w.line("{");
            w.indent();
            let inner_expr = cs_decode_expr(ty, opts);
            w.line(&format!("{local} = {inner_expr};"));
            emit_cs_validation(w, constraints, local, field_name);
            w.dedent();
            w.line("}");
        }
        _ => {
            let decode_expr = cs_decode_expr(ty, opts);
            w.line(&format!("{local} = {decode_expr};"));
            emit_cs_validation(w, constraints, local, field_name);
        }
    }
}

fn emit_cs_validation(
    w:           &mut IndentWriter,
    constraints: &[Constraint],
    expr:        &str,
    field_name:  &str,
) {
    for c in constraints {
        if let Some(check) = cs_constraint_check(c, expr) {
            let msg = constraint_description(c);
            w.line(&format!("if (!({check}))"));
            w.indent();
            w.line(&format!("throw new CborValidationException({:?}, {msg:?});", field_name));
            w.dedent();
        }
    }
}

fn cs_decode_expr(ty: &TypeRef, opts: &CodegenOptions) -> String {
    match ty {
        TypeRef::Primitive(p) => cs_decode_call(p),
        TypeRef::Named(n)     => format!("{}.Decode(reader)", to_pascal_case(n)),
        TypeRef::Tagged(_, inner) => cs_decode_expr(inner, opts),
        TypeRef::Choice(_)    => "reader.ReadInt64() /* choice */".into(),
    }
}

fn cs_decode_call(p: &Primitive) -> String {
    match p {
        Primitive::Bool      => "reader.ReadBoolean()".into(),
        Primitive::Null | Primitive::Undefined => "reader.ReadNull()".into(),
        Primitive::Uint      => "reader.ReadUInt64()".into(),
        Primitive::Int       => "reader.ReadInt64()".into(),
        Primitive::Float16   => "reader.ReadSingle()".into(),
        Primitive::Float32   => "reader.ReadSingle()".into(),
        Primitive::Float64 | Primitive::Float => "reader.ReadDouble()".into(),
        Primitive::Tstr      => "reader.ReadTextString()".into(),
        Primitive::Bstr | Primitive::Any => "reader.ReadByteString()".into(),
    }
}

// ── Constraint checks ─────────────────────────────────────────────────────────

fn cs_constraint_check(c: &Constraint, expr: &str) -> Option<String> {
    match c {
        Constraint::SizeExact(n) =>
            Some(format!("{expr}.Length == {n}")),
        Constraint::SizeRange { min, max } => match (min, max) {
            (Some(lo), Some(hi)) => Some(format!("{expr}.Length >= {lo} && {expr}.Length <= {hi}")),
            (Some(lo), None)     => Some(format!("{expr}.Length >= {lo}")),
            (None, Some(hi))     => Some(format!("{expr}.Length <= {hi}")),
            (None, None)         => None,
        },
        Constraint::ValueRangeInt { min, max, inclusive } => {
            let op = if *inclusive { "=" } else { "" };
            match (min, max) {
                (Some(lo), Some(hi)) => Some(format!("{expr} >={op} {lo} && {expr} <={op} {hi}")),
                (Some(lo), None)     => Some(format!("{expr} >={op} {lo}")),
                (None, Some(hi))     => Some(format!("{expr} <={op} {hi}")),
                (None, None)         => None,
            }
        }
        Constraint::ValueRangeUint { min, max, inclusive } => {
            let op = if *inclusive { "=" } else { "" };
            match (min, max) {
                (Some(lo), Some(hi)) => Some(format!("{expr} >={op} {lo}UL && {expr} <={op} {hi}UL")),
                (Some(lo), None)     => Some(format!("{expr} >={op} {lo}UL")),
                (None, Some(hi))     => Some(format!("{expr} <={op} {hi}UL")),
                (None, None)         => None,
            }
        }
        Constraint::Eq(v)  => Some(format!("{expr} == {}", cs_literal(v))),
        Constraint::Ne(v)  => Some(format!("{expr} != {}", cs_literal(v))),
        Constraint::Regexp { hook: Some(h), .. } => Some(format!("{h}({expr})")),
        _ => None,
    }
}

fn constraint_description(c: &Constraint) -> String {
    match c {
        Constraint::SizeExact(n)    => format!("length must be {n}"),
        Constraint::SizeRange { min, max } => format!("length out of range ({min:?}..{max:?})"),
        Constraint::ValueRangeInt { min, max, .. } => format!("value out of range ({min:?}..{max:?})"),
        Constraint::ValueRangeUint { min, max, .. } => format!("value out of range ({min:?}..{max:?})"),
        Constraint::Eq(v)  => format!("must equal {}", cs_literal(v)),
        Constraint::Ne(v)  => format!("must not equal {}", cs_literal(v)),
        _                  => "constraint violated".into(),
    }
}

fn cs_literal(v: &LiteralValue) -> String {
    match v {
        LiteralValue::Bool(b)  => b.to_string().to_lowercase(),
        LiteralValue::Null     => "null".into(),
        LiteralValue::Uint(n)  => format!("{n}UL"),
        LiteralValue::Int(n)   => format!("{n}L"),
        LiteralValue::Float(f) => format!("{f}"),
        LiteralValue::Text(s)  => format!("{s:?}"),
        LiteralValue::Bytes(_) => "null /* bytes */".into(),
    }
}

// ── C# type helpers ───────────────────────────────────────────────────────────

fn cs_field_type(ty: &TypeRef, occ: &Occurrence, opts: &CodegenOptions) -> String {
    let base = cs_typeref(ty, opts);
    match occ {
        Occurrence::Optional => format!("{base}?"),
        Occurrence::ZeroOrMore { .. } | Occurrence::OneOrMore { .. }
        | Occurrence::Bounded { .. } => format!("List<{base}>"),
        Occurrence::Required => base,
    }
}

fn cs_default_value(ty: &TypeRef, occ: &Occurrence, opts: &CodegenOptions) -> String {
    match occ {
        Occurrence::Optional => "null".into(),
        Occurrence::ZeroOrMore { .. } | Occurrence::OneOrMore { .. }
        | Occurrence::Bounded { .. } => format!("new List<{}>() ", cs_typeref(ty, opts)),
        Occurrence::Required => cs_type_default(ty, opts),
    }
}

fn cs_type_default(ty: &TypeRef, opts: &CodegenOptions) -> String {
    match ty {
        TypeRef::Primitive(p) => match p {
            Primitive::Bool    => "false".into(),
            Primitive::Uint    => "0UL".into(),
            Primitive::Int     => "0L".into(),
            Primitive::Float16 | Primitive::Float32 => "0.0f".into(),
            Primitive::Float64 | Primitive::Float   => "0.0".into(),
            Primitive::Tstr    => "string.Empty".into(),
            Primitive::Bstr | Primitive::Any => "Array.Empty<byte>()".into(),
            Primitive::Null | Primitive::Undefined => "null!".into(),
        },
        TypeRef::Named(n)         => format!("new {}()", to_pascal_case(n)),
        TypeRef::Tagged(_, inner) => cs_type_default(inner, opts),
        TypeRef::Choice(_)        => "null!".into(),
    }
}

fn cs_typeref(ty: &TypeRef, opts: &CodegenOptions) -> String {
    match ty {
        TypeRef::Primitive(p)     => cs_primitive(p).to_owned(),
        TypeRef::Named(n)         => to_pascal_case(n),
        TypeRef::Tagged(_, inner) => cs_typeref(inner, opts),
        TypeRef::Choice(cs)       => cs.first()
            .map(|c| cs_typeref(c, opts))
            .unwrap_or_else(|| "object".into()),
    }
}

fn cs_primitive(p: &Primitive) -> &'static str {
    match p {
        Primitive::Bool      => "bool",
        Primitive::Null | Primitive::Undefined => "object",
        Primitive::Uint      => "ulong",
        Primitive::Int       => "long",
        Primitive::Float16   => "float",
        Primitive::Float32   => "float",
        Primitive::Float64 | Primitive::Float => "double",
        Primitive::Tstr      => "string",
        Primitive::Bstr | Primitive::Any => "byte[]",
    }
}

// ── Test file ─────────────────────────────────────────────────────────────────

fn emit_tests(module: &IrModule, opts: &CodegenOptions) -> String {
    let name  = module.name.as_str();
    let ns    = to_pascal_case(name);
    let mut w = IndentWriter::new(4);

    for l in cddlc_codegen::header_lines(opts) {
        w.line(&format!("// {l}"));
    }
    w.line("// xUnit roundtrip tests");
    w.blank();
    w.line("using System;");
    w.line("using System.Collections.Generic;");
    if opts.is_json() {
        w.line("using System.Text.Json;");
    } else {
        w.line("using System.Formats.Cbor;");
    }
    w.line("using Xunit;");
    w.blank();
    w.line(&format!("namespace {ns}.Tests;"));
    w.blank();
    w.line("public sealed class RoundtripTests");
    w.line("{");
    w.indent();

    for (_, def) in &module.types {
        emit_type_tests(&mut w, def, opts);
        w.blank();
    }

    w.dedent();
    w.line("}");
    w.finish()
}

fn emit_type_tests(w: &mut IndentWriter, def: &TypeDef, opts: &CodegenOptions) {
    match def {
        TypeDef::Struct(s) => emit_struct_tests(w, s, opts),
        TypeDef::Enum(e)   => emit_enum_tests(w, e, opts),
        TypeDef::Alias(a)  => emit_alias_tests(w, a, opts),
        TypeDef::Array(a)  => emit_array_tests(w, a, opts),
        TypeDef::Map(_)    => {}
    }
}

fn emit_struct_tests(w: &mut IndentWriter, s: &StructDef, opts: &CodegenOptions) {
    let type_name = to_pascal_case(&s.name);
    let test_pfx  = to_pascal_case(&s.name);

    // Tier 1: default roundtrip
    w.line("[Fact]");
    w.line(&format!("public void {test_pfx}_Roundtrip_Default()"));
    w.line("{");
    w.indent();
    w.line(&format!("var original = new {type_name}"));
    w.line("{");
    w.indent();
    for f in &s.fields {
        let pname = to_pascal_case(&f.name);
        let val   = cs_type_default(&f.ty, opts);
        match &f.occurrence {
            Occurrence::Optional => w.line(&format!("{pname} = null,")),
            _ => w.line(&format!("{pname} = {val},")),
        }
    }
    w.dedent();
    w.line("};");
    if opts.is_json() { emit_roundtrip_assert_json(w, &type_name); } else { emit_roundtrip_assert(w, &type_name); }
    w.dedent();
    w.line("}");
    w.blank();

    // Tier 2: explicit values
    w.line("[Fact]");
    w.line(&format!("public void {test_pfx}_Roundtrip_Explicit()"));
    w.line("{");
    w.indent();
    w.line(&format!("var original = new {type_name}"));
    w.line("{");
    w.indent();
    for f in &s.fields {
        let pname = to_pascal_case(&f.name);
        let val   = cs_explicit_value(&f.ty, &f.occurrence, opts);
        w.line(&format!("{pname} = {val},"));
    }
    w.dedent();
    w.line("};");
    if opts.is_json() { emit_roundtrip_assert_json(w, &type_name); } else { emit_roundtrip_assert(w, &type_name); }
    w.dedent();
    w.line("}");

    if !opts.is_json() {
        if let Some(tag) = s.tagged {
            w.blank();
            w.line("[Fact]");
            w.line(&format!("public void {test_pfx}_Encode_HasTag_{}()", tag.0));
            w.line("{");
            w.indent();
            w.line(&format!("var obj = new {type_name}();"));
            w.line("var writer = new CborWriter();");
            w.line("obj.Encode(writer);");
            w.line("var bytes = writer.Encode();");
            w.line(&format!("// First bytes should contain tag {}", tag.0));
            w.line("Assert.NotEmpty(bytes);");
            w.dedent();
            w.line("}");
        }
    }
}

fn emit_enum_tests(w: &mut IndentWriter, e: &EnumDef, opts: &CodegenOptions) {
    let type_name = to_pascal_case(&e.name);

    for v in &e.variants {
        let vname = to_pascal_case(&v.name);
        w.line("[Fact]");
        w.line(&format!("public void {type_name}_{vname}_Roundtrip()"));
        w.line("{");
        w.indent();

        if opts.is_json() {
            let construct = match &v.ty {
                TypeRef::Primitive(Primitive::Tstr | Primitive::Null) => {
                    let cddl_str = v.name.to_lowercase().replace('_', "-");
                    format!("{type_name}.Create{vname}({cddl_str:?})")
                }
                TypeRef::Primitive(Primitive::Uint) =>
                    format!("{type_name}.Create{vname}(0UL)"),
                TypeRef::Primitive(Primitive::Int) =>
                    format!("{type_name}.Create{vname}(0L)"),
                TypeRef::Primitive(Primitive::Bool) =>
                    format!("{type_name}.Create{vname}(false)"),
                _ => format!("{type_name}.Create{vname}()"),
            };
            w.line(&format!("var original = {construct};"));
            w.line("var bytes = original.ToJson();");
            w.line(&format!("var decoded = {type_name}.FromJson(bytes);"));
            w.line("Assert.NotNull(decoded);");
        } else {
            let construct = match &v.ty {
                TypeRef::Primitive(Primitive::Tstr | Primitive::Null) =>
                    format!("{type_name}.{vname}.Instance"),
                TypeRef::Primitive(Primitive::Uint) =>
                    format!("new {type_name}.{vname}(0UL)"),
                TypeRef::Primitive(Primitive::Int) =>
                    format!("new {type_name}.{vname}(0L)"),
                TypeRef::Primitive(Primitive::Bool) =>
                    format!("new {type_name}.{vname}(false)"),
                _ => format!("{type_name}.{vname}.Instance"),
            };
            w.line(&format!("var original = {construct};"));
            w.line("var writer = new CborWriter();");
            w.line("original.Encode(writer);");
            w.line("var reader = new CborReader(writer.Encode());");
            w.line(&format!("var decoded = {type_name}.Decode(reader);"));
            w.line("Assert.IsType(original.GetType(), decoded);");
        }
        w.dedent();
        w.line("}");
        w.blank();
    }
}

fn emit_alias_tests(w: &mut IndentWriter, a: &AliasDef, opts: &CodegenOptions) {
    let type_name = to_pascal_case(&a.name);

    w.line("[Fact]");
    w.line(&format!("public void {type_name}_Roundtrip_Default()"));
    w.line("{");
    w.indent();

    // For constrained aliases, produce a valid value
    let val = if a.constraints.is_empty() {
        cs_type_default(&a.ty, opts)
    } else {
        cs_valid_constrained_value(&a.constraints, &a.ty, opts)
    };

    if a.constraints.is_empty() && a.tagged.is_none() {
        w.line(&format!("var original = new {type_name} {{ Value = {val} }};"));
    } else {
        w.line(&format!("var original = new {type_name}({val});"));
    }
    if opts.is_json() { emit_roundtrip_assert_json(w, &type_name); } else { emit_roundtrip_assert(w, &type_name); }
    w.dedent();
    w.line("}");

    // Constraint rejection test
    if !a.constraints.is_empty() {
        w.blank();
        w.line("[Fact]");
        w.line(&format!("public void {type_name}_Invalid_ThrowsValidation()"));
        w.line("{");
        w.indent();
        let bad = cs_invalid_constrained_value(&a.constraints, &a.ty, opts);
        let exc_name = if opts.is_json() { "JsonValidationException" } else { "CborValidationException" };
        w.line(&format!(
            "Assert.Throws<{exc_name}>(() => new {type_name}({bad}));"
        ));
        w.dedent();
        w.line("}");
    }
}

fn emit_array_tests(w: &mut IndentWriter, a: &ArrayDef, opts: &CodegenOptions) {
    let type_name = to_pascal_case(&a.name);

    w.line("[Fact]");
    w.line(&format!("public void {type_name}_Roundtrip_Empty()"));
    w.line("{");
    w.indent();
    w.line(&format!("var original = new {type_name}();"));
    if opts.is_json() { emit_roundtrip_assert_json(w, &type_name); } else { emit_roundtrip_assert(w, &type_name); }
    w.dedent();
    w.line("}");
}

fn emit_roundtrip_assert(w: &mut IndentWriter, type_name: &str) {
    w.line("var writer = new CborWriter();");
    w.line("original.Encode(writer);");
    w.line("var reader = new CborReader(writer.Encode());");
    w.line(&format!("var decoded = {type_name}.Decode(reader);"));
    w.line("Assert.NotNull(decoded);");
}

fn emit_roundtrip_assert_json(w: &mut IndentWriter, type_name: &str) {
    w.line("var bytes = original.ToJson();");
    w.line(&format!("var decoded = {type_name}.FromJson(bytes);"));
    w.line("Assert.NotNull(decoded);");
}

