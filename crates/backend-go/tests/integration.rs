#[test]
fn test_constraints_checked_by_validate() {
    let g = compile("dev = tstr .size 16\nmsg = { temp: int .ge -40 .le 85, ? note: tstr .size 8 }");
    assert!(g.source.contains("func (v Dev) Validate() error {\n\tx := string(v)\n\tif !(len(x) == 16) {"), "{}", g.source);
    assert!(g.source.contains("if !(v.Temp >= -40) {"), "{}", g.source);
    assert!(g.source.contains("if !(v.Temp <= 85) {"), "{}", g.source);
    assert!(g.source.contains("if v.Note != nil {\n\t\tif !(len(*v.Note) == 8) {"), "{}", g.source);
    assert!(g.tests.contains("if _, err := Dev(\"aaaaaaaaaaaaaaaaa\").Encode(); err == nil {"), "{}", g.tests);
}

#[test]
fn test_enum_kinds_constructors_and_literals() {
    let g = compile("level = uint / \"off\"\nprio = 1 / 2 / -3");
    assert!(g.source.contains("type Level struct {\n\tKind LevelKind\n\tUint uint64\n}"), "{}", g.source);
    assert!(g.source.contains("LevelKindUint LevelKind = iota\n\tLevelKindOff\n"), "{}", g.source);
    assert!(g.source.contains("func NewLevelUint(x uint64) Level { return Level{Kind: LevelKindUint, Uint: x} }"), "{}", g.source);
    assert!(g.source.contains("func NewLevelOff() Level { return Level{Kind: LevelKindOff} }"), "{}", g.source);
    assert!(g.source.contains("case LevelKindOff:\n\t\treturn marshal(\"off\")"), "{}", g.source);
    // Integer literals are written and matched as integers, negatives too.
    assert!(g.source.contains("return marshal(uint64(2))"), "{}", g.source);
    assert!(g.source.contains("return marshal(int64(-3))"), "{}", g.source);
    assert!(g.source.contains("case -3:\n\t\t\t*v = Prio{Kind: PrioKindVariant3}"), "{}", g.source);
    assert!(g.tests.contains("func TestPrioRejectsUnnamedInteger(t *testing.T) {\n\tif _, err := DecodePrio([]byte{0}); err == nil {"), "{}", g.tests);
}

#[test]
fn test_tags_written_and_checked() {
    let g = compile("stamp = #6.1(uint)\nmsg = { at: #6.1(uint) }\ntimes = [* #6.1(uint)]");
    assert!(g.source.contains("return tagWith(1)(marshal(uint64(v)))"), "{}", g.source);
    assert!(g.source.contains("r, err := untag(data, 1, \"Stamp\")"), "{}", g.source);
    assert!(g.source.contains("e.put(\"at\")(tagWith(1)(marshal(v.At)))"), "{}", g.source);
    assert!(g.source.contains("r, err := untag(r, 1, \"Msg.at\")"), "{}", g.source);
    assert!(g.source.contains("type Times []uint64"), "{}", g.source);
    assert!(g.source.contains("encodeEach([]uint64(v), func(x uint64) ([]byte, error) { return tagWith(1)(marshal(x)) })"), "{}", g.source);
    // JSON has no tags.
    let j = json("stamp = #6.1(uint)");
    assert!(j.source.contains("return marshal(uint64(v))"), "{}", j.source);
}

#[test]
fn test_nil_member_is_null() {
    let g = compile("m = { ? gone: nil, always: nil }");
    assert!(g.source.contains("\tGone   *Null\n\tAlways Null\n"), "{}", g.source);
    // A present optional nil member is decoded (null), not treated as absent.
    assert!(g.source.contains("if r, ok := m[\"gone\"]; ok {"), "{}", g.source);
    assert!(g.source.contains("e.put(\"always\")(encNull())"), "{}", g.source);
}

#[test]
fn test_json_bytes_in_enum_decoded_from_text() {
    let j = json("blob = bstr / \"none\"");
    assert!(j.source.contains("if b, err := decBytes(r, \"Blob\"); err == nil {"), "{}", j.source);
}

