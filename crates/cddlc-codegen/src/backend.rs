/// Serialization format.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Format {
    /// CBOR (RFC 8949) — default.
    #[default]
    Cbor,
    /// JSON (RFC 8259), with byte strings base64url-encoded per RFC 8949 §6.1.
    Json,
}

/// Code-generation options passed to every backend.
#[derive(Debug, Clone)]
pub struct CodegenOptions {
    /// Target language (informational — each backend ignores others).
    pub lang:         Language,
    /// Serialization format.
    pub format:       Format,
    /// CBOR runtime library name (e.g. "minicbor", "ciborium").
    pub runtime:      String,
    /// Memory allocation strategy.
    pub alloc:        AllocStrategy,
    /// Emit deterministic (dCBOR) encoding.
    pub dcbor:        bool,
    /// Rust: emit `#![no_std]` + no heap allocation.
    pub no_std:       bool,
    /// Maximum nesting depth for decoder stack.
    pub depth_limit:  usize,
    /// Namespace / module prefix for emitted symbols.
    pub namespace:    Option<String>,
    /// Default capacity for unbounded sequences.
    pub max_array:    usize,
    /// Default capacity for unbounded strings.
    pub max_str:      usize,
    /// What made the code, for every generated file's header after the `@generated`
    /// line: the cddlc release, commit, branch and remote, and the inputs
    /// (dgtlrift/cddlc#10). See [`header_lines`].
    pub provenance:   Vec<String>,
    /// The comment block at the top of the CDDL source (a copyright or license
    /// notice, say), one line each without the `;`, repeated in every generated
    /// file's header. See [`cddl_boilerplate`].
    pub boilerplate:  Vec<String>,
    /// Java: SE or Jakarta EE output.
    pub java_flavor:  JavaFlavor,
}

/// The first line of every generated file.
pub const GENERATED: &str = "@generated by cddlc — do not edit manually";

/// The lines every generated file opens with: [`GENERATED`], then
/// `opts.provenance` (dgtlrift/cddlc#10), then a blank line and
/// `opts.boilerplate` when there is one. [`header_comment`] writes them as comments.
pub fn header_lines(opts: &CodegenOptions) -> Vec<String> {
    let mut lines = vec![GENERATED.to_owned()];
    lines.extend(opts.provenance.iter().cloned());
    if !opts.boilerplate.is_empty() {
        lines.push(String::new());
        lines.extend(opts.boilerplate.iter().cloned());
    }
    lines
}

/// A language's comment syntax, for [`header_comment`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CommentStyle {
    /// `// line` (Rust, C++, C#, TypeScript, Dart, Go, Java, go.mod).
    Slash,
    /// `# line` (Python, TOML, YAML, CMake, shell).
    Hash,
    /// `-- line` (Lua).
    DashDash,
    /// A C block: `/*`, ` * line`, ` */`. A `*/` in a line becomes `* /`.
    CBlock,
    /// An XML block: `<!--`, `  line`, `-->`. A `--` in a line becomes `- -`,
    /// which XML comments can't contain.
    Xml,
}

/// [`header_lines`] as comment lines in `style`, without trailing whitespace.
pub fn header_comment(opts: &CodegenOptions, style: CommentStyle) -> Vec<String> {
    comment_lines(&header_lines(opts), style)
}

/// [`header_comment`] joined with newlines, ending in one.
pub fn header_text(opts: &CodegenOptions, style: CommentStyle) -> String {
    header_comment(opts, style).iter().map(|l| format!("{l}\n")).collect()
}

/// `lines` as comment lines in `style`, without trailing whitespace.
pub fn comment_lines(lines: &[String], style: CommentStyle) -> Vec<String> {
    let line = |prefix: &str, l: &str| format!("{prefix} {l}").trim_end().to_owned();
    match style {
        CommentStyle::Slash    => lines.iter().map(|l| line("//", l)).collect(),
        CommentStyle::Hash     => lines.iter().map(|l| line("#", l)).collect(),
        CommentStyle::DashDash => lines.iter().map(|l| line("--", l)).collect(),
        CommentStyle::CBlock => std::iter::once("/*".to_owned())
            .chain(lines.iter().map(|l| line(" *", &l.replace("*/", "* /"))))
            .chain(std::iter::once(" */".to_owned()))
            .collect(),
        CommentStyle::Xml => std::iter::once("<!--".to_owned())
            .chain(lines.iter().map(|l| {
                let mut t = l.clone();
                while t.contains("--") { t = t.replace("--", "- -"); }
                if t.ends_with('-') { t.push(' '); }
                format!("  {t}").trim_end().to_owned()
            }))
            .chain(std::iter::once("-->".to_owned()))
            .collect(),
    }
}

/// [`header_lines`] as the members of a JSON array, one per line at `indent`
/// spaces, for JSON files, which have no comments: they carry the header as a
/// `"//"` member, which npm and the interop harnesses ignore.
pub fn header_json(opts: &CodegenOptions, indent: usize) -> String {
    let pad = " ".repeat(indent);
    header_lines(opts)
        .iter()
        .map(|l| {
            let mut q = String::new();
            for c in l.chars() {
                match c {
                    '"' => q.push_str("\\\""),
                    '\\' => q.push_str("\\\\"),
                    c if (c as u32) < 0x20 => q.push_str(&format!("\\u{:04x}", c as u32)),
                    c => q.push(c),
                }
            }
            format!("{pad}\"{q}\"")
        })
        .collect::<Vec<_>>()
        .join(",\n")
}

/// The comment block at the top of a CDDL source, for [`CodegenOptions::boilerplate`]:
/// the `;` lines before the first blank line, each without its `;`s and one space.
/// None when a rule follows the block directly (it is then that rule's comment).
/// Annotation lines (`; @import ...`, `; @doc ...`) are left out.
pub fn cddl_boilerplate(src: &str) -> Vec<String> {
    let mut lines = src.lines().skip_while(|l| l.trim().is_empty());
    let mut block = Vec::new();
    for l in lines.by_ref() {
        let t = l.trim_start();
        let Some(rest) = t.strip_prefix(';') else {
            if t.is_empty() { break; }
            return Vec::new(); // a rule follows: the block is its comment
        };
        let rest = rest.trim_start_matches(';');
        let rest = rest.strip_prefix(' ').unwrap_or(rest).trim_end();
        if !rest.trim_start().starts_with('@') {
            block.push(rest.to_owned());
        }
    }
    while block.last().is_some_and(|l| l.is_empty()) { block.pop(); }
    while block.first().is_some_and(|l| l.is_empty()) { block.remove(0); }
    block
}

impl Default for CodegenOptions {
    fn default() -> Self {
        Self {
            lang:        Language::Rust,
            format:      Format::Cbor,
            runtime:     "minicbor".into(),
            alloc:       AllocStrategy::Arena,
            dcbor:       false,
            no_std:      false,
            depth_limit: 16,
            namespace:   None,
            max_array:   16,
            max_str:     64,
            provenance:  Vec::new(),
            boilerplate: Vec::new(),
            java_flavor: JavaFlavor::Se,
        }
    }
}

impl CodegenOptions {
    pub fn is_json(&self) -> bool { self.format == Format::Json }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language { Rust, C, Cpp, CSharp, Python, Dart, Go, Java, Lua }

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AllocStrategy { Stack, Arena, Heap }

/// Java: plain Java SE, or Jakarta EE (Bean Validation annotations, and JSON-B
/// serializers for JSON).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum JavaFlavor {
    #[default]
    Se,
    Ee,
}

/// A generated source file.
#[derive(Debug, Clone)]
pub struct GeneratedFile {
    /// Relative path within the output directory (e.g. `"types.rs"`).
    pub path:    String,
    /// File contents.
    pub content: String,
}

/// The result of running a backend over an [`IrModule`].
#[derive(Debug, Clone)]
pub struct CodegenOutput {
    pub files: Vec<GeneratedFile>,
}

impl CodegenOutput {
    pub fn single(path: impl Into<String>, content: impl Into<String>) -> Self {
        Self { files: vec![GeneratedFile { path: path.into(), content: content.into() }] }
    }
}

/// The backend trait every language target must implement.
pub trait Backend {
    /// Human-readable language name.
    fn language_name(&self) -> &str;

    /// File extension for primary output (e.g. `"rs"`, `"h"`).
    fn file_extension(&self) -> &str;

    /// Generate all files for the given IR module.
    fn generate(
        &self,
        module: &cddlc_ir::IrModule,
        opts:   &CodegenOptions,
    ) -> Result<CodegenOutput, crate::CodegenError>;
}

/// Error from a backend.
#[derive(Debug)]
pub struct CodegenError {
    pub message: String,
}

impl CodegenError {
    pub fn new(msg: impl Into<String>) -> Self {
        Self { message: msg.into() }
    }
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for CodegenError {}
